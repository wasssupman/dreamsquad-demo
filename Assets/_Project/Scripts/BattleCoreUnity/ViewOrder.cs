namespace Wassup.BattleCoreUnity
{
    // battle-core-rebuild unit 5a — **뷰 사이의 순서 계약을 한 화면에 모은 곳.**
    //
    // 코어 `EventOrder` 의 뷰 쪽 짝이다. 코어가 담당자 사이의 차례를 구독 숫자로 적듯,
    // Unity 층은 뷰 풀 사이의 차례를 여기 적는다. 「풀마다 자기 구독」(계약 12)이라
    // 통합 뷰가 없고, 그러면 **누가 먼저 받느냐**를 말할 자리가 사라진다.
    //
    // ⚠ C# 이벤트 등록 순서에 기대지 않는다. 그 순서는 곧 **씬 컴포넌트의 나열 순서**이고,
    // 하이어라키에서 오브젝트 하나를 끌어 올리면 연출 순서가 조용히 뒤집힌다. 그 버그는
    // 씬을 만진 날이 아니라 그 다음 플레이에서 나온다.
    //
    // 오늘의 전순서(X3 — 「뷰 갱신 직전에 도약 채널을 비워야 1프레임 팝이 없다」):
    //   도약 연출 → 바닥(해저드·픽업·사직서) → 유닛 동기 → 투사체 → 일반 VFX·빔
    //   → 숫자·히트바 → 상태 표식·오라 → 오버헤드 → 손패(unit 7c)
    //
    // unit 6c — **바닥에 깔리는 것은 유닛 앞, 몸에 붙는 것은 유닛 뒤**다. 장판이 유닛 뒤에
    // 서면 그 프레임에 태어난 유닛이 장판 밑에 깔리고, 표식이 유닛 앞에 서면 같은 틱에 태어난
    // 유닛의 앵커가 아직 없어 표식이 첫 프레임을 놓친다.
    // 도약이 유닛 동기보다 **먼저**인 이유: 도약은 그 유닛의 뷰 위치를 덮어쓰고(비행),
    // 유닛 동기가 그 덮어쓴 값을 읽는다. 순서가 뒤집히면 비행이 한 프레임 늦어 착지점에서
    // 출발점으로 튀는 팝이 보인다.
    //
    // 값 사이를 10 씩 띄운 것은 나중에 사이에 끼울 자리를 남기기 위해서다.
    public static class ViewOrder
    {
        /// <summary>관측·로그. 누구보다 먼저 — 뷰가 무엇을 하기 전의 사건을 남긴다.</summary>
        public const int Trace = 0;

        /// <summary>도약 연출. 비행 중 유닛 뷰 위치를 덮어쓴다(X3).</summary>
        public const int Leap = 10;

        /// <summary>
        /// 바닥에 깔리는 것 — 존 장판·길막·픽업·사직서(unit 6c). **유닛보다 먼저**: 같은 틱에
        /// 장판이 깔리고 적이 태어나면, 장판이 먼저 서야 적이 그 위에 선다.
        /// </summary>
        public const int Board = 15;

        /// <summary>유닛 뷰 생성·회수·모션. 도약의 덮어쓰기를 읽는다.</summary>
        public const int Unit = 20;

        /// <summary>투사체 뷰 생성·회수.</summary>
        public const int Projectile = 30;

        /// <summary>
        /// 일반 VFX·빔(unit 6c) — 타격 이펙트·총구·배치 링·실드 원샷. 유닛·탄 뷰가 선 뒤라야
        /// 앵커(손·총구)를 물을 수 있다.
        /// </summary>
        public const int Effect = 35;

        /// <summary>피해 숫자·히트바. 유닛 뷰가 선 뒤라야 앵커가 있다.</summary>
        public const int Damage = 40;

        /// <summary>
        /// 몸에 붙는 상태 표식·오라(unit 6c). **유닛 뒤**다 — 같은 틱에 태어난 유닛에게 거는
        /// 표식은 그 유닛 뷰가 선 뒤에야 앵커가 있다.
        /// </summary>
        public const int Status = 45;

        /// <summary>오버헤드 UI·오라. 위의 결과를 읽어 화면에 얹는다.</summary>
        public const int Overhead = 50;

        /// <summary>
        /// 손패·각성 항아리·선택 패널의 부착 카드 줄(unit 7c — uGUI 캔버스). **오버헤드 뒤**다: 카드 사건 한 건이 몸에 붙는 것
        /// (표식 = `Status` · 오버헤드 카드 아이콘 = `Overhead`)을 먼저 세운 뒤, 손패가 같은 사건으로 자기 창을 다시 읽는다.
        /// 부착 범위 링은 사건 구독자가 아니다 — 손패 드래그가 오버레이에 **민다**(바닥 채널, 배치 링에 양보).
        /// </summary>
        public const int Hand = 55;

        /// <summary>
        /// 전투 사운드(unit 5c). **그림이 선 뒤에 소리**다 — 같은 프레임 안이라 귀로는
        /// 구분되지 않지만, 순서가 정해져 있어야 「소리는 나는데 그림이 없다」가 생겼을 때
        /// 어느 쪽이 먼저였나를 묻지 않아도 된다.
        /// </summary>
        public const int Audio = 60;

        /// <summary>
        /// 판 종료 → 결과 화면(unit 5c). **맨 뒤** — 이번 틱을 모든 뷰가 반영한 뒤에
        /// 화면을 덮는다. 먼저 덮으면 마지막 킬의 숫자·죽는 모션이 결과 화면 밑에 깔린다.
        /// </summary>
        public const int Outcome = 70;
    }
}
